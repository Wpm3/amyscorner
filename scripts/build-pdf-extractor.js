#!/usr/bin/env node
/**
 * Generates src/parsers/pdf/extractorHtml.generated.ts: a self-contained HTML page
 * that embeds pdf.js (legacy build) so PDFs can be parsed fully offline inside a
 * hidden WebView on both iOS and Android. Runs automatically on `npm install`.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const build = path.join(root, 'node_modules', 'pdfjs-dist', 'legacy', 'build');
const lib = fs.readFileSync(path.join(build, 'pdf.min.mjs'), 'utf8');
const worker = fs.readFileSync(path.join(build, 'pdf.worker.min.mjs'), 'utf8');

// Safe to embed inside a <script> element.
const embed = (s) => JSON.stringify(s).replace(/<\/(script)/gi, '<\\/$1').replace(/<!--/g, '<\\!--');

const page = `<!doctype html><html><head><meta charset="utf-8"></head><body><script>
(function () {
  var LIB_SRC = ${embed(lib)};
  var WORKER_SRC = ${embed(worker)};
  function post(msg) {
    var s = JSON.stringify(msg);
    if (window.ReactNativeWebView) window.ReactNativeWebView.postMessage(s);
    else if (window.__onPdfMessage) window.__onPdfMessage(s);
    else if (window.parent && window.parent !== window) window.parent.postMessage({ __unfoldPdf: true, payload: s }, '*');
  }
  var libPromise = null;
  function loadLib() {
    if (!libPromise) {
      libPromise = (async function () {
        var workerUrl = URL.createObjectURL(new Blob([WORKER_SRC], { type: 'text/javascript' }));
        // Load the worker module on the main thread: pdf.js then uses its in-thread
        // "fake worker", which avoids module-worker support differences between WebViews.
        globalThis.pdfjsWorker = await import(workerUrl);
        var libUrl = URL.createObjectURL(new Blob([LIB_SRC], { type: 'text/javascript' }));
        var pdfjs = await import(libUrl);
        pdfjs.GlobalWorkerOptions.workerSrc = workerUrl;
        return pdfjs;
      })();
    }
    return libPromise;
  }
  function b64ToBytes(b64) {
    var bin = atob(b64);
    var out = new Uint8Array(bin.length);
    for (var i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
    return out;
  }
  async function extract(id, b64) {
    try {
      var pdfjs = await loadLib();
      var task = pdfjs.getDocument({ data: b64ToBytes(b64), isEvalSupported: false, disableFontFace: true, useSystemFonts: false, stopAtErrors: false });
      var doc = await task.promise;
      var meta = null;
      try { meta = await doc.getMetadata(); } catch (e) {}
      var info = (meta && meta.info) || {};
      post({ type: 'meta', id: id, total: doc.numPages, title: info.Title || null, author: info.Author || null });
      var batch = [];
      for (var p = 1; p <= doc.numPages; p++) {
        var page = await doc.getPage(p);
        var vp = page.getViewport({ scale: 1 });
        var content = await page.getTextContent();
        var items = [];
        for (var k = 0; k < content.items.length; k++) {
          var it = content.items[k];
          if (!it.str) continue;
          var t = pdfjs.Util.transform(vp.transform, it.transform);
          items.push({ str: it.str, x: t[4], y: t[5], w: it.width * vp.scale, h: Math.hypot(t[2], t[3]) || it.height });
        }
        batch.push({ width: vp.width, height: vp.height, items: items });
        page.cleanup();
        if (batch.length >= 8 || p === doc.numPages) {
          post({ type: 'pages', id: id, pages: batch, done: p, total: doc.numPages });
          batch = [];
        }
      }
      post({ type: 'done', id: id });
      try { await task.destroy(); } catch (e) {}
    } catch (err) {
      var msg = String((err && err.message) || err);
      if (err && err.name === 'PasswordException') msg = 'This PDF is password protected.';
      post({ type: 'error', id: id, message: msg });
    }
  }
  function onMessage(ev) {
    var data;
    try { data = typeof ev.data === 'string' ? JSON.parse(ev.data) : ev.data; } catch (e) { return; }
    if (data && data.type === 'extract') extract(data.id, data.base64);
  }
  window.addEventListener('message', onMessage);
  document.addEventListener('message', onMessage);
  window.__extractPdf = extract;
  loadLib().then(function () { post({ type: 'ready' }); }, function (e) { post({ type: 'error', id: null, message: 'Failed to load PDF engine: ' + e }); });
})();
</script></body></html>`;

const out = path.join(root, 'src', 'parsers', 'pdf', 'extractorHtml.generated.ts');
fs.writeFileSync(
  out,
  '// AUTO-GENERATED by scripts/build-pdf-extractor.js — do not edit.\n/* eslint-disable */\nexport const PDF_EXTRACTOR_HTML: string = ' +
    JSON.stringify(page) +
    ';\n',
);
console.log('Wrote', path.relative(root, out), (fs.statSync(out).size / 1024 / 1024).toFixed(2) + ' MB');
